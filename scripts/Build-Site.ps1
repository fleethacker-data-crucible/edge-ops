<#
.SYNOPSIS
  Assembles the static GitHub Pages site into _site/ from catalog.json.
.DESCRIPTION
  Compatible with Windows PowerShell 5.1 and PowerShell 7 (Linux runners).
  Copies index.html, assets/ and the ui-kit runtime (kit.css, fonts, favicon), regenerates assets/catalog-data.js,
  renders templates/pages/tool-page.html once per tool, and writes 404.html and .nojekyll.
.EXAMPLE
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\scripts\Build-Site.ps1
#>
[CmdletBinding()]
param(
  [string]$Root = '',   # default: repo root (set below; $PSScriptRoot is empty in param defaults under 5.1 -File)
  [string]$OutDir = '_site',
  [string]$BasePath = ''   # e.g. '/edge-ops/' for an absolute 404 base; empty = relative
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Split-Path -Parent $PSScriptRoot }
Set-StrictMode -Version 2

function Enc([object]$v) { if ($null -eq $v) { return '' } return [System.Net.WebUtility]::HtmlEncode([string]$v) }
# Optional catalog properties: under Set-StrictMode -Version 2 a missing property throws, so read them through PSObject.Properties.
function Get-Opt([object]$Obj, [string]$Name) {
  if ($null -eq $Obj) { return $null }
  $p = $Obj.PSObject.Properties[$Name]
  if ($null -eq $p) { return $null }
  return $p.Value
}
function Write-Utf8([string]$Path, [string]$Text) {
  $enc = New-Object System.Text.UTF8Encoding($false)
  [System.IO.File]::WriteAllText($Path, $Text, $enc)
}

$catalogPath = Join-Path $Root 'catalog.json'
$catalogJson = [System.IO.File]::ReadAllText($catalogPath)
$catalog = $catalogJson | ConvertFrom-Json

$out = Join-Path $Root $OutDir
if (Test-Path $out) { Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory -Path $out | Out-Null
New-Item -ItemType Directory -Path (Join-Path $out 'tools') | Out-Null

Copy-Item (Join-Path $Root 'index.html') $out
Copy-Item (Join-Path $Root 'catalog.json') $out
Copy-Item (Join-Path $Root 'assets') (Join-Path $out 'assets') -Recurse
Remove-Item (Join-Path $out 'assets/themes/README.md') -ErrorAction SilentlyContinue  # docs, not site content
Remove-Item (Join-Path $out 'assets/emblems/README.md') -ErrorAction SilentlyContinue  # docs, not site content
# UI kit runtime only (no demo/dev files); pages reference it relatively as ui-kit/ or ../ui-kit/.
$kitSrc = Join-Path $Root 'ui-kit'
$kitOut = Join-Path $out 'ui-kit'
New-Item -ItemType Directory -Path $kitOut | Out-Null
foreach ($f in @('kit.css','VERSION','README.md')) { Copy-Item (Join-Path $kitSrc $f) $kitOut }
Copy-Item (Join-Path $kitSrc 'fonts') (Join-Path $kitOut 'fonts') -Recurse
Copy-Item (Join-Path $kitSrc 'assets') (Join-Path $kitOut 'assets') -Recurse
Write-Utf8 (Join-Path $out 'assets/catalog-data.js') ("/* Generated by scripts/Build-Site.ps1 */`nwindow.EDGE_OPS_CATALOG = " + $catalogJson.Trim() + ";`n")
Write-Utf8 (Join-Path $out '.nojekyll') ''

$cats = @{ 'browser-only'='Browser-only'; 'ps-host-browser-ui'='PowerShell host + browser UI'; 'data-ai'='Data &amp; AI'; 'security'='Security'; 'support'='Support repos'; 'gpu-host'='GPU or build machine' }
# key, label, badge class, "need" wording
$flags = @(
  @('ps51','Windows PowerShell 5.1','green'), @('chromeEngine','Chrome/Edge browser','green'),
  @('batch','.bat launcher','green'), @('vbs','.vbs helper','yellow'),
  @('admin','Admin rights','red'), @('installs','Installs / third-party runtimes','red'),
  @('network','Network access','yellow'), @('csharpRuntimeCompile','Runtime C# compile (Add-Type)','yellow'),
  @('gpu','GPU','yellow'), @('outlook','Microsoft Outlook','yellow')
)

$template = [System.IO.File]::ReadAllText((Join-Path $Root 'templates/pages/tool-page.html'))
$count = 0
foreach ($t in $catalog.tools) {
  $port = Get-Opt $t 'defaultPort'; $launcher = Get-Opt $t 'launcher'; $releases = Get-Opt $t 'releases'
  $external = Get-Opt $t 'external'; $installNote = Get-Opt $t 'installNote'
  $req = Get-Opt $t 'requirements'
  $badges = New-Object System.Text.StringBuilder
  $rows = New-Object System.Text.StringBuilder
  foreach ($f in $flags) {
    $val = [bool](Get-Opt $req $f[0])
    if ($val) { [void]$badges.Append('<span class="badge ' + $f[2] + '">' + (Enc $f[1]) + '</span>') }
    $yn = if ($val) { 'Yes' } else { 'No' }
    [void]$rows.Append('<tr><td>' + (Enc $f[1]) + '</td><td>' + $yn + '</td></tr>')
  }
  if (-not [bool](Get-Opt $req 'admin')) { [void]$badges.Append('<span class="badge green">No admin</span>') }
  # defaultPort: a number, 'auto' (picks a free loopback port), 'local' (local server, port not stated), or null (no server).
  if ($port -is [string] -and $port -eq 'auto') {
    [void]$badges.Append('<span class="badge grey">free port</span>')
    $portText = 'Opens on a free 127.0.0.1 port.'
  } elseif ($port -is [string] -and $port -eq 'local') {
    $portText = 'Starts a local server on 127.0.0.1 and opens your browser.'
  } elseif ($port -and -not ($port -is [string])) {
    [void]$badges.Append('<span class="badge grey">port ' + $port + '</span>')
    $portText = 'Your browser opens to <code>http://127.0.0.1:' + $port + '/</code> (or the next free loopback port). Close the console to stop.'
  } else {
    $portText = 'No local server needed.'
  }
  # A server with no browser UI (requirements.chromeEngine false) gets neutral wording; an optional runNote replaces it outright.
  if ($port -and -not ($port -is [string]) -and -not [bool](Get-Opt $req 'chromeEngine')) {
    $portText = 'Starts a local server on <code>http://127.0.0.1:' + $port + '/</code> (or the next free loopback port), with no browser UI. Press Ctrl+C in the console to stop.'
  }
  $runNote = Get-Opt $t 'runNote'
  if ($runNote) { $portText = Enc $runNote }
  [void]$badges.Append('<span class="badge grey">' + (Enc $t.status) + '</span>')

  if ($releases) { $rel = '<a href="' + (Enc $releases) + '">Releases &rarr; latest</a>' }
  else { $rel = 'not published on GitHub (see source below)' }
  $ext = ''
  if ($external) { $ext = ' &middot; External source: <code>' + (Enc (Get-Opt $t 'externalSource')) + '</code>' }
  $catLabel = $cats[[string]$t.category]; if (-not $catLabel) { $catLabel = Enc $t.category }

  # Decorative emblem (the h1 names the tool): assets/emblems/<id>.svg when the file exists, else nothing.
  $emblem = ''
  if (Test-Path -LiteralPath (Join-Path $Root ('assets/emblems/' + [string]$t.id + '.svg')) -PathType Leaf) {
    $emblem = '<img class="emblem" src="../assets/emblems/' + (Enc $t.id) + '.svg" alt="" aria-hidden="true" width="48" height="48">'
  }
  # For agents (CONVENTIONS.md, CLI and API for agents): only when the catalog records it; nothing is assumed.
  $automation = ''
  $au = Get-Opt $t 'automation'
  if ($au) {
    $api = [string](Get-Opt $au 'api')
    $apiText = if ($api -eq 'openai-v1') { 'Yes: OpenAI-compatible <code>/v1</code> on 127.0.0.1' } elseif ($api) { 'Yes: local HTTP API on 127.0.0.1 (' + (Enc $api) + ')' } else { 'No' }
    $describe = [string](Get-Opt $au 'describe')
    $yes = { param($v) if ([bool]$v) { 'Yes' } else { 'No' } }
    $automation = '<section><h2>For agents</h2><table class="req"><tbody>' +
      '<tr><td>Command line (every action a person can take)</td><td>' + (& $yes (Get-Opt $au 'cli')) + '</td></tr>' +
      '<tr><td>Machine-readable output (<code>--json</code>)</td><td>' + (& $yes (Get-Opt $au 'json')) + '</td></tr>' +
      '<tr><td>API</td><td>' + $apiText + '</td></tr>' +
      '<tr><td>MCP server</td><td>' + (& $yes (Get-Opt $au 'mcp')) + '</td></tr>' +
      '<tr><td>Lists its commands</td><td>' + $(if ($describe) { '<code>' + (Enc $describe) + '</code>' } else { 'No' }) + '</td></tr>' +
      '</tbody></table></section>'
  }
  $html = $template
  $map = [ordered]@{
    '{{NAME}}'=(Enc $t.name); '{{SUMMARY}}'=(Enc $t.summary); '{{CATEGORY}}'=$catLabel
    '{{BADGES}}'=$badges.ToString(); '{{REQ_ROWS}}'=$rows.ToString(); '{{LAUNCHER}}'=(Enc $launcher)
    '{{PORT_TEXT}}'=$portText; '{{RELEASE_LINK}}'=$rel; '{{REPO}}'=(Enc $t.repo)
    '{{EXTERNAL_NOTE}}'=$ext; '{{STATUS}}'=(Enc $t.status); '{{EMBLEM}}'=$emblem; '{{AUTOMATION}}'=$automation
  }
  foreach ($k in $map.Keys) { $html = $html.Replace($k, [string]$map[$k]) }
  if ([bool](Get-Opt $req 'installs')) {
    # Tools that need third-party installs don't run on whitelisted workstations: no zip/launcher steps.
    $note = if ($installNote) { [string]$installNote } else { 'Needs third-party installs; see the repo README.' }
    $html = [regex]::Replace($html, '(?s)<section><h2>Run on whitelisted Windows</h2>.*?</section>', ('<section><h2>Run</h2><p>' + (Enc $note) + ' Not for app-whitelisted workstations.</p></section>'))
  } elseif (-not $launcher) {
    # Repos with nothing to run yet (no UI or no code): replace the run steps with one line.
    $html = [regex]::Replace($html, '(?s)<section><h2>Run on whitelisted Windows</h2>.*?</section>', '<section><h2>Run</h2><p>Nothing to launch yet. See the source repository.</p></section>')
  }
  Write-Utf8 (Join-Path $out ('tools/' + $t.id + '.html')) $html
  $count++
}

$base = $BasePath
$nf = [System.IO.File]::ReadAllText((Join-Path $Root 'templates/pages/404.html')).Replace('{{BASE}}', $base)
Write-Utf8 (Join-Path $out '404.html') $nf

Write-Host ("Built {0} with {1} tool pages." -f $out, $count)
