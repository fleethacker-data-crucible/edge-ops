<#
.SYNOPSIS
  Assembles the static GitHub Pages site into _site/ from catalog.json.
.DESCRIPTION
  Compatible with Windows PowerShell 5.1 and PowerShell 7 (Linux runners).
  Copies index.html and assets/, regenerates assets/catalog-data.js,
  renders templates/pages/tool-page.html once per tool, and writes 404.html and .nojekyll.
.EXAMPLE
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\scripts\Build-Site.ps1
#>
[CmdletBinding()]
param(
  [string]$Root = (Split-Path -Parent $PSScriptRoot),
  [string]$OutDir = '_site',
  [string]$BasePath = ''   # e.g. '/edge-ops/' for an absolute 404 base; empty = relative
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2

function Enc([object]$v) { if ($null -eq $v) { return '' } return [System.Net.WebUtility]::HtmlEncode([string]$v) }
function Write-Utf8([string]$Path, [string]$Text) {
  $enc = New-Object System.Text.UTF8Encoding($false)
  [System.IO.File]::WriteAllText($Path, $Text, $enc)
}

$catalogPath = Join-Path $Root 'catalog.json'
$catalogJson = [System.IO.File]::ReadAllText($catalogPath)
$catalog = $catalogJson | ConvertFrom-Json

$out = Join-Path $Root $OutDir
if (Test-Path $out) { Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory -Path $out | Out-Null
New-Item -ItemType Directory -Path (Join-Path $out 'tools') | Out-Null

Copy-Item (Join-Path $Root 'index.html') $out
Copy-Item (Join-Path $Root 'catalog.json') $out
Copy-Item (Join-Path $Root 'assets') (Join-Path $out 'assets') -Recurse
Write-Utf8 (Join-Path $out 'assets/catalog-data.js') ("/* Generated by scripts/Build-Site.ps1 */`nwindow.EDGE_OPS_CATALOG = " + $catalogJson.Trim() + ";`n")
Write-Utf8 (Join-Path $out '.nojekyll') ''

$cats = @{ 'browser-only'='Browser-only'; 'ps-host-browser-ui'='PowerShell host + browser UI'; 'data-ai'='Data &amp; AI'; 'security'='Security' }
# key, label, badge class, "need" wording
$flags = @(
  @('ps51','Windows PowerShell 5.1','ok'), @('chromeEngine','Chrome/Edge browser','ok'),
  @('batch','.bat launcher','ok'), @('vbs','.vbs helper','warn'),
  @('admin','Admin rights','bad'), @('installs','Installs / third-party runtimes','bad'),
  @('network','Network access','warn'), @('csharpRuntimeCompile','Runtime C# compile (Add-Type)','warn'),
  @('gpu','GPU','warn'), @('outlook','Microsoft Outlook','warn')
)

$template = [System.IO.File]::ReadAllText((Join-Path $Root 'templates/pages/tool-page.html'))
$count = 0
foreach ($t in $catalog.tools) {
  $req = $t.requirements
  $badges = New-Object System.Text.StringBuilder
  $rows = New-Object System.Text.StringBuilder
  foreach ($f in $flags) {
    $val = [bool]($req.($f[0]))
    if ($val) { [void]$badges.Append('<span class="b ' + $f[2] + '">' + (Enc $f[1]) + '</span>') }
    $yn = if ($val) { 'Yes' } else { 'No' }
    [void]$rows.Append('<tr><td>' + (Enc $f[1]) + '</td><td>' + $yn + '</td></tr>')
  }
  if (-not [bool]$req.admin) { [void]$badges.Append('<span class="b ok">No admin</span>') }
  if ($t.defaultPort) {
    [void]$badges.Append('<span class="b">port ' + $t.defaultPort + '</span>')
    $portText = 'Your browser opens to <code>http://127.0.0.1:' + $t.defaultPort + '/</code> (or the next free loopback port). Close the console to stop.'
  } else {
    $portText = 'No local server needed.'
  }
  [void]$badges.Append('<span class="b">' + (Enc $t.status) + '</span>')

  if ($t.releases) { $rel = '<a href="' + (Enc $t.releases) + '">Releases &rarr; latest</a>' }
  else { $rel = 'not published on GitHub (see source below)' }
  $ext = ''
  if ($t.external) { $ext = ' &middot; External source: <code>' + (Enc $t.externalSource) + '</code>' }
  $catLabel = $cats[[string]$t.category]; if (-not $catLabel) { $catLabel = Enc $t.category }

  $html = $template
  $map = [ordered]@{
    '{{NAME}}'=(Enc $t.name); '{{SUMMARY}}'=(Enc $t.summary); '{{CATEGORY}}'=$catLabel
    '{{BADGES}}'=$badges.ToString(); '{{REQ_ROWS}}'=$rows.ToString(); '{{LAUNCHER}}'=(Enc $t.launcher)
    '{{PORT_TEXT}}'=$portText; '{{RELEASE_LINK}}'=$rel; '{{REPO}}'=(Enc $t.repo)
    '{{EXTERNAL_NOTE}}'=$ext; '{{STATUS}}'=(Enc $t.status)
  }
  foreach ($k in $map.Keys) { $html = $html.Replace($k, [string]$map[$k]) }
  Write-Utf8 (Join-Path $out ('tools/' + $t.id + '.html')) $html
  $count++
}

$base = $BasePath
$nf = [System.IO.File]::ReadAllText((Join-Path $Root 'templates/pages/404.html')).Replace('{{BASE}}', $base)
Write-Utf8 (Join-Path $out '404.html') $nf

Write-Host ("Built {0} with {1} tool pages." -f $out, $count)
